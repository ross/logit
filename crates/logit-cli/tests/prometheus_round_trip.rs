fn fixtures_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/prometheus")
}

fn read_fixture(name: &str, ext: &str) -> Vec<u8> {
    let path = fixtures_dir().join(format!("{name}.{ext}"));
    std::fs::read(&path).unwrap_or_else(|e| panic!("reading fixture {}: {e}", path.display()))
}

/// The three families `prometheus_in` always synthesizes -- excluded from every comparison in this
/// file by name (permitted normalization 11 above), never asserted equal at all.
const SYNTHETIC_FAMILIES: [&str; 3] = ["up", "scrape_duration_seconds", "scrape_samples_scraped"];

/// Reparses `body` (the bytes a real scrape of `prometheus_out` actually returned), drops the three
/// synthetic families, re-renders, then substitutes `target_addr`'s literal `host:port` with the
/// placeholder `{port}` the fixture files use -- the module doc's normalizations 8 and 11, applied
/// to the *actual* output before comparing against `.expected` (never the other way around: the
/// fixture is never mutated to match the run).
fn strip_synthetic_and_placeholder_port(
    body: &str,
    dialect: Dialect,
    target_addr: SocketAddr,
) -> String {
    let families = text::parse(body.as_bytes(), dialect)
        .unwrap_or_else(|e| panic!("actual prometheus_out output must parse: {e}\nbody:\n{body}"));
    let filtered: Vec<_> =
        families.into_iter().filter(|f| !SYNTHETIC_FAMILIES.contains(&f.name.as_str())).collect();
    let mut out = Vec::new();
    text::write(&filtered, dialect, &mut out);
    let rendered = String::from_utf8(out).expect("exposition must be utf-8");
    rendered.replace(&target_addr.to_string(), "{port}")
}

/// What a canned connection serves: one fixed body under one fixed `Content-Type`, forever -- the
/// scraped target this file's fixed-point cases pretend to be. Modeled on
/// `crates/logit-inputs/src/prometheus.rs`'s own `canned_server` test helper (same `hyper`
/// server-side stack), duplicated rather than shared across the crate boundary, the same reasoning
/// `otlp_round_trip.rs`'s own module doc gives for living in `logit-cli` at all.
async fn canned_server(body: Bytes, content_type: &'static str) -> SocketAddr {
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    let addr = listener.local_addr().unwrap();
    tokio::spawn(async move {
        loop {
            let Ok((stream, _)) = listener.accept().await else { return };
            let io = TokioIo::new(stream);
            let body = body.clone();
            tokio::spawn(async move {
                let service = service_fn(move |_req: Request<Incoming>| {
                    let body = body.clone();
                    async move {
                        Ok::<_, Infallible>(
                            Response::builder()
                                .status(200)
                                .header("content-type", content_type)
                                .body(Full::new(body))
                                .unwrap(),
                        )
                    }
                });
                let _ =
                    hyper::server::conn::http1::Builder::new().serve_connection(io, service).await;
            });
        }
    });
    addr
}

/// A plain `reqwest` client with gzip transparently disabled -- a gzipped body should arrive
/// exactly as `prometheus_out` wrote it, not silently inflated by the client, matching
/// `crates/logit-outputs/src/prometheus.rs`'s own test helper.
fn http_client() -> reqwest::Client {
    reqwest::Client::builder().no_gzip().build().expect("a default client always builds")
}

/// Scrapes `target_addr` (a [`canned_server`]) with a real, bound [`PrometheusInput`] on a very
/// short interval, waits for the one `EventBatch` it forwards through a bare [`Fanout`], then feeds
/// that batch into a fresh [`PrometheusOutput`] and returns the exposition body a real `reqwest` GET
/// against it gets back for `accept`, alongside `target_addr` itself (what the caller substitutes
/// for `{port}`).
async fn scrape_relay_and_fetch(target_addr: SocketAddr, accept: &str) -> (String, SocketAddr) {
    let mut input = PrometheusInput::new(
        vec![format!("http://{target_addr}/metrics")],
        Duration::from_millis(20),
    );
    let (tx, mut rx) = mpsc::channel(16);
    let sink = Fanout::new(vec![tx]);
    tokio::spawn(async move {
        let _ = input.run(sink).await;
    });

    // `PrometheusInput::run` swallows its first (immediate) tick, so the first real scrape lands
    // after one full `interval` -- a generous timeout well past that single 20ms wait.
    let delivered = tokio::time::timeout(Duration::from_secs(2), rx.recv())
        .await
        .expect("prometheus_in should scrape and forward a batch")
        .expect("the Fanout channel should not have closed");
    let batch = logit_pipeline::unwrap_batch(delivered);

    let (body, _addr) = expose_and_fetch(std::slice::from_ref(&batch), accept).await;
    (body, target_addr)
}

/// Binds a fresh [`PrometheusOutput`], sends every batch in `batches` into it, then fetches its
/// exposition with `accept`. Returns the response body and the sink's own bound address (unused by
/// the fixed-point cases, which care about the *target's* address instead -- see
/// [`scrape_relay_and_fetch`]; the pipeline cases below use this directly and ignore the target
/// address entirely).
async fn expose_and_fetch(batches: &[EventBatch], accept: &str) -> (String, SocketAddr) {
    let mut output = PrometheusOutput::new("127.0.0.1:0");
    output.bind().await.expect("binding prometheus_out");
    let addr = output.local_addr().expect("bind() should leave a real address behind");
    for batch in batches {
        output.send(batch).await.expect("send never fails");
    }

    let client = http_client();
    let response = client
        .get(format!("http://{addr}/metrics"))
        .header("accept", accept)
        .send()
        .await
        .expect("the scrape request should reach prometheus_out");
    assert_eq!(response.status(), 200);
    let body = response.text().await.expect("body should be text");
    (body, addr)
}

const ACCEPT_TEXT: &str = "text/plain";
const ACCEPT_OM: &str = "application/openmetrics-text";

fn dialect_of(ext: &str) -> Dialect {
    match ext {
        "text" => Dialect::Text0_0_4,
        "om" => Dialect::OpenMetrics1_0,
        other => panic!("unknown fixture dialect extension {other:?}"),
    }
}

fn content_type_of(ext: &str) -> &'static str {
    dialect_of(ext).content_type()
}

fn accept_of(ext: &str) -> &'static str {
    match ext {
        "text" => ACCEPT_TEXT,
        "om" => ACCEPT_OM,
        other => panic!("unknown fixture dialect extension {other:?}"),
    }
}

/// One fixed-point or dialect-change case: scrape `name`'s `.{in_ext}.in` body, request the
/// exposition back in `out_ext`'s dialect, and assert the result -- synthetic families stripped,
/// the scraped target's real ephemeral port replaced with `{port}` -- equals `name`'s
/// `.{out_ext}.expected` byte for byte.
async fn assert_fixture_round_trips(name: &str, in_ext: &str, out_ext: &str) {
    let body = read_fixture(name, &format!("{in_ext}.in"));
    let target_addr = canned_server(Bytes::from(body), content_type_of(in_ext)).await;
    let (actual_raw, _) = scrape_relay_and_fetch(target_addr, accept_of(out_ext)).await;
    let actual =
        strip_synthetic_and_placeholder_port(&actual_raw, dialect_of(out_ext), target_addr);
    let expected = String::from_utf8(read_fixture(name, &format!("{out_ext}.expected")))
        .expect("fixture must be utf-8");
    assert_eq!(actual, expected, "{name}: {in_ext} -> {out_ext} mismatch");
}

