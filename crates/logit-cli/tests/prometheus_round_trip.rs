//! `prometheus_in -> prometheus_out` round trip over real sockets -- the Prometheus counterpart to
//! `syslog_round_trip.rs`/`otlp_round_trip.rs`. A canned `hyper` server plays the scraped target
//! (serving a fixture's `.in` body under the right `Content-Type`); a real, bound [`PrometheusInput`]
//! scrapes it and forwards through a [`Fanout`] into a real [`PrometheusOutput`], which a `reqwest`
//! client then scrapes in turn with a chosen `Accept`. `docs/plans/prometheus-scrape-and-exposition.md`'s
//! W5 workstream.
//!
//! ## Permitted normalizations (recorded here, and in `docs/adr/prometheus-scrape-and-exposition.md`'s
//! "Permitted normalizations for this pair" section, which this list transcribes)
//!
//! 1. **Family/series reordering.** Families sorted by name, series within a family sorted by
//!    label set.
//! 2. **Label reordering**, sorted by rendered (post-sanitization) name.
//! 3. **Float formatting**: shortest round-trip representation (`1.0` renders as `1`).
//! 4. **`# TYPE x untyped` synthesized** for a family that arrived with no `# TYPE` metadata at
//!    all. Exercised by `untyped_no_type`.
//! 5. **`_created`, `# UNIT`, and exemplars dropped** when the *output* dialect is text 0.0.4 --
//!    none of the three has a text 0.0.4 wire representation.
//! 6. **`# EOF` presence**: written only when the output dialect is OpenMetrics.
//! 7. **Blank lines and non-`HELP`/`TYPE`/`UNIT` comments dropped.**
//! 8. **An `instance` label is added**, `host:port` of the scraped target -- exactly as
//!    Prometheus's own scrape does. Present on every fixture's expected output as the literal
//!    placeholder `{port}` (see "Fixture corpus" below).
//! 9. **A counter sample name gains a `_total` suffix if it lacked one**, in either dialect.
//!    Exercised by `counter_no_total`.
//! 10. **A cross-dialect family-type substitution** when the output dialect lacks the wire type
//!     the model attribute names (`untyped`<->`unknown`, `info`/`stateset`/`gaugehistogram`
//!     down-converted on text egress, `_info` re-appended on OM egress). Exercised by
//!     `dialect_text_untyped_to_om` and `dialect_om_types_to_text`.
//! 11. **The three synthetic families `prometheus_in` always adds** (`up`,
//!     `scrape_duration_seconds`, `scrape_samples_scraped`) are excluded from every comparison in
//!     this file by name, not asserted equal at all -- see [`strip_synthetic_and_placeholder_port`].
//!
//! ## Fixture corpus (`tests/fixtures/prometheus/`)
//!
//! One input body per case, drawn from the Prometheus exposition-format docs' and the OpenMetrics
//! spec's own worked examples (the same strings `crates/logit-proto/tests/prometheus_fixed_point.rs`
//! already embeds), named `<name>.<in-dialect>.in` (`text` or `om`), and one expected exposition
//! body per requested output dialect, named `<name>.<out-dialect>.expected`. For a same-dialect
//! fixed point the two extensions match (`gauge.text.in` / `gauge.text.expected`); for a
//! dialect-change case they differ (`dialect_text_untyped_to_om.text.in` /
//! `dialect_text_untyped_to_om.om.expected`), exercising normalization 10 above. Every `.expected`
//! file carries the literal placeholder `{port}` wherever the real test substitutes the scraped
//! target's actual ephemeral `instance` value (normalization 8) -- there is no `SAME AS INPUT`
//! sentinel in this corpus, since the added `instance` label means no fixture is ever byte-identical
//! to its own input, unlike `syslog_round_trip.rs`'s corpus.
//!
//! Each `.expected` file was generated by running the real `logit_proto::prometheus` codec
//! (`parse` -> `families_to_events` -> `events_to_families` with an injected `instance` resource
//! attribute of literally `{port}` -> `write`) rather than hand-computed, so it is correct against
//! the same codec `crates/logit-proto/tests/prometheus_fixed_point.rs` already proves fixed-point
//! and grammar-fuzzed -- this file's job is to prove the *real sockets and components* compose to
//! the identical result, not to re-litigate the codec's own correctness.

