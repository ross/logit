//! `prometheus_in -> prometheus_out` over real sockets. A canned `hyper` server plays the scraped
//! target, serving a fixture's `.in` body under its dialect's `Content-Type`; a bound
//! [`PrometheusInput`] scrapes it into a [`Fanout`], the batch goes into a real [`ExposeOutput`],
//! and a `reqwest` client scrapes that with a chosen `Accept`.
//!
//! The result must equal the fixture's `.expected` body byte for byte. The differences allowed
//! between `.in` and `.expected` are the list under `crates/logit-proto/src/prometheus/mod.rs`'s
//! "Permitted normalizations" heading. Two more are this file's own, applied to the actual output
//! only by [`strip_synthetic_and_placeholder_port`]: the three synthetic families `prometheus_in`
//! adds are excluded by name, and the target's ephemeral `host:port` becomes the literal `{port}`.
//!
//! ## Fixture corpus (`tests/fixtures/prometheus/`)
//!
//! Inputs are the Prometheus exposition-format docs' and the OpenMetrics spec's worked examples
//! (the strings `crates/logit-proto/tests/prometheus_fixed_point.rs` embeds), named
//! `<name>.<in-dialect>.in` with `text` or `om`; the expected body is
//! `<name>.<out-dialect>.expected`. Matching extensions are a same-dialect fixed point, differing
//! ones a dialect change. There is no `SAME AS INPUT` sentinel: the added `instance` label means
//! no output is byte-identical to its input.
//!
//! Each `.expected` file was generated by the real `logit_proto::prometheus` codec (`parse` ->
//! `families_to_events` -> `events_to_families` with an `instance` resource attribute of `{port}`
//! -> `write`), then checked line by line so every difference from its `.in` is a permitted
//! normalization. Metadata-line order is fixed per dialect (OpenMetrics writes `# TYPE` first,
//! text 0.0.4 writes `# HELP` first), as `crates/logit-outputs/src/prometheus.rs`'s
//! `EXPECTED_TEXT` and `EXPECTED_OPENMETRICS` show. The codec's own correctness is
//! `prometheus_fixed_point.rs`'s job; this file proves the real sockets and components compose to
//! the same result.
//!
//! What each fixture exercises beyond ordering, float formatting, and `instance`:
//!
//! - `counter_no_total` (text): the bare `requests` sample gains `_total`; a wire millisecond
//!   timestamp survives unchanged.
//! - `counter_created`, `histogram`, `full_openmetrics` (OM -> OM): `_created`, `# UNIT`,
//!   exemplars, and `info`/`stateset`/`gaugehistogram`/`unknown` all survive when neither leg is
//!   text 0.0.4, so dropping them is dialect-triggered, not unconditional.
//! - `gauge`, `escaped_and_special` (text): `-Inf`/`NaN`/`+Inf` spellings and escaped label values.
//! - `summary` (text): quantile labels sorted.
//! - `untyped_no_type` (text): `# TYPE bare_metric untyped` synthesized for a family with no
//!   metadata line.
//! - `dialect_text_untyped_to_om` (text -> OM): `untyped` becomes `unknown`.
//! - `dialect_om_types_to_text` (OM -> text): `unknown`, `info` (with an `_info`-suffixed sample),
//!   `stateset`, and `gaugehistogram` down-convert, and a counter's `# UNIT`, `_created`, and
//!   exemplar are dropped.

