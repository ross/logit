/// `statsd_in -> aggregate(temporality: cumulative) -> prometheus_out`: two `hits:1|c` datagrams
/// absorb into one cumulative counter, which `prometheus_out` renders as `hits_total 2` plus a
/// `_created` line (OpenMetrics only) -- the ADR's "Temporality is `aggregate`'s job" section's own
/// worked example.
#[tokio::test]
async fn statsd_through_cumulative_aggregate_renders_a_cumulative_counter_with_created() {
    // Bind-drop-rebind: `StatsdInput` exposes no `local_addr()` accessor (its `UdpListener` is
    // private), so an ephemeral port is reserved with a throwaway socket first, the same idiom
    // `otlp_round_trip.rs`'s `ephemeral_addr()` uses for TCP.
    let probe = tokio::net::UdpSocket::bind("127.0.0.1:0").await.unwrap();
    let addr = probe.local_addr().unwrap();
    drop(probe);

    let mut input = StatsdInput::new(addr.to_string());
    input.bind().await.expect("binding statsd_in");
    let (tx, mut rx) = mpsc::channel(16);
    let sink = Fanout::new(vec![tx]);
    tokio::spawn(async move {
        let _ = input.run(sink).await;
    });

    let sender = tokio::net::UdpSocket::bind("127.0.0.1:0").await.unwrap();
    sender.send_to(b"hits:1|c", addr).await.expect("send should reach statsd_in");
    sender.send_to(b"hits:1|c", addr).await.expect("send should reach statsd_in");

    let mut aggregator = Aggregator::new(Duration::from_secs(3600))
        .with_temporality(AggregateTemporality::Cumulative)
        .with_series_retention(5, 10_000);

    // `UdpListenerConfig::default`'s `batch_flush_interval` (100ms) may coalesce both datagrams
    // into a single batch rather than delivering one per send, so this collects events (not
    // batches) until both increments have arrived, rather than assuming a 1:1 batch:datagram
    // correspondence.
    let mut absorbed_events = 0;
    while absorbed_events < 2 {
        let delivered = tokio::time::timeout(Duration::from_secs(2), rx.recv())
            .await
            .expect("statsd_in should forward both increments")
            .expect("the Fanout channel should not have closed");
        let batch = logit_pipeline::unwrap_batch(delivered);
        let resource = batch.resource.clone();
        for event in batch.events {
            absorbed_events += 1;
            let absorbed = aggregator.process(&resource, event);
            assert!(
                absorbed.is_none(),
                "a delta Sum under cumulative temporality must be absorbed"
            );
        }
    }

    let flushed = aggregator.flush(1_700_000_000_000_000_000);
    assert!(!flushed.is_empty(), "two absorbed increments must produce a flushed batch");
    let batches: Vec<EventBatch> = flushed
        .into_iter()
        .map(|(resource, scope, events)| EventBatch {
            resource,
            scope,
            events: events.into_iter().map(|(event, _links)| event).collect(),
        })
        .collect();

    let (body, _addr) = expose_and_fetch(&batches, ACCEPT_OM).await;
    assert!(
        body.contains("hits_total 2"),
        "expected a cumulative hits_total 2 sample, got:\n{body}"
    );
    assert!(
        body.contains("hits_created"),
        "temporality: cumulative sets start_timestamp, which prometheus_out renders as \
         _created in OpenMetrics; got:\n{body}"
    );
}

/// `internal -> aggregate(temporality: cumulative) -> prometheus_out`: `logit`'s own self-telemetry
/// (an ordinary `logit.component.*` counter, drained by `internal` like any other component's) still
/// renders as an ordinary counter family -- proving `prometheus_out` is fed by the graph like any
/// other sink, not a second telemetry representation, per
/// [ADR `internal-telemetry-as-pipeline-events`](../../../docs/adr/internal-telemetry-as-pipeline-events.md)'s
/// amendment.
#[tokio::test]
async fn internal_telemetry_through_cumulative_aggregate_renders_a_logit_component_counter() {
    let registry = Registry::new();
    let telemetry = registry.telemetry_for("probe", "statsd_in", "listener");
    telemetry.count("logit.component.batches.sent", 3.0, &[]);

    let mut input = InternalInput::new(Duration::from_millis(20), registry);
    let (tx, mut rx) = mpsc::channel(16);
    let sink = Fanout::new(vec![tx]);
    tokio::spawn(async move {
        let _ = input.run(sink).await;
    });

    let delivered = tokio::time::timeout(Duration::from_secs(2), rx.recv())
        .await
        .expect("internal should drain and forward a batch")
        .expect("the Fanout channel should not have closed");
    let batch = logit_pipeline::unwrap_batch(delivered);

    let mut aggregator = Aggregator::new(Duration::from_secs(3600))
        .with_temporality(AggregateTemporality::Cumulative)
        .with_series_retention(5, 10_000);

    let mut passthrough = Vec::new();
    for event in batch.events {
        if let Some(forwarded) = aggregator.process(&batch.resource, event) {
            passthrough.push(forwarded);
        }
    }

    let flushed = aggregator.flush(1_700_000_000_000_000_000);
    let mut batches: Vec<EventBatch> = flushed
        .into_iter()
        .map(|(resource, scope, events)| EventBatch {
            resource,
            scope,
            events: events.into_iter().map(|(event, _links)| event).collect(),
        })
        .collect();
    if !passthrough.is_empty() {
        batches.push(EventBatch {
            resource: batch.resource.clone(),
            scope: batch.scope.clone(),
            events: passthrough,
        });
    }

    let (body, _addr) = expose_and_fetch(&batches, ACCEPT_TEXT).await;
    assert!(
        body.contains("logit_component_batches_sent_total"),
        "expected at least one logit_component_* counter family, got:\n{body}"
    );
}
