/// `statsd_in -> aggregate(temporality: cumulative) -> prometheus_out`: two `hits:1|c` datagrams
/// become one `hits_total 2` plus an OpenMetrics `_created` line, per ADR
/// `prometheus-scrape-and-exposition`'s "Temporality is `aggregate`'s job" section.
#[tokio::test]
async fn statsd_through_cumulative_aggregate_renders_a_cumulative_counter_with_created() {
    let mut input = StatsdInput::new("127.0.0.1:0");
    input.bind().await.expect("binding statsd_in");
    let addr = input.local_addr().expect("bind() should leave a real address behind");
    let (tx, mut rx) = mpsc::channel(16);
    let sink = Fanout::new(vec![tx]);
    tokio::spawn(async move {
        let _ = input.run(sink).await;
    });

    let sender = tokio::net::UdpSocket::bind("127.0.0.1:0").await.unwrap();
    sender.send_to(b"hits:1|c", addr).await.expect("send should reach statsd_in");
    sender.send_to(b"hits:1|c", addr).await.expect("send should reach statsd_in");

    let mut aggregator = Aggregator::new(Duration::from_secs(3600))
        .with_temporality(AggregateTemporality::Cumulative)
        .with_series_retention(5, 10_000);

    // The default 100ms `batch_flush_interval` may coalesce both datagrams into one batch, so
    // this counts events, not batches.
    let mut absorbed_events = 0;
    while absorbed_events < 2 {
        let delivered = tokio::time::timeout(Duration::from_secs(2), rx.recv())
            .await
            .expect("statsd_in should forward both increments")
            .expect("the Fanout channel should not have closed");
        let batch = logit_pipeline::unwrap_batch(delivered);
        let resource = batch.resource.clone();
        for mut event in batch.events {
            absorbed_events += 1;
            let forwarded = aggregator.process(&resource, &mut event);
            assert!(!forwarded, "a delta Sum under cumulative temporality must be absorbed");
        }
    }

    let flushed = aggregator.flush(1_700_000_000_000_000_000);
    assert!(!flushed.is_empty(), "two absorbed increments must produce a flushed batch");
    let batches: Vec<EventBatch> = flushed
        .into_iter()
        .map(|(resource, scope, events)| EventBatch {
            resource,
            scope,
            events: events.into_iter().map(|(event, _links)| event).collect(),
        })
        .collect();

    let (body, _addr) = expose_and_fetch(&batches, ACCEPT_OM).await;
    assert!(
        body.contains("hits_total 2"),
        "expected a cumulative hits_total 2 sample, got:\n{body}"
    );
    // `hits_created` must hold a real unix-seconds timestamp: cumulative temporality stamps
    // `start_timestamp` from the series' first-seen wall-clock time, so a value below 1.6e9
    // (2020-09-13) means the wrong field, or none, was rendered.
    let created_line = body
        .lines()
        .find(|line| line.starts_with("hits_created"))
        .unwrap_or_else(|| panic!("expected a hits_created line, got:\n{body}"));
    let created_value: f64 = created_line
        .split_whitespace()
        .nth(1)
        .unwrap_or_else(|| panic!("hits_created line has no value: {created_line:?}"))
        .parse()
        .unwrap_or_else(|e| panic!("hits_created value should parse as a float: {e}"));
    assert!(
        created_value > 1.6e9,
        "hits_created {created_value} is not a plausible unix-seconds timestamp, in:\n{body}"
    );
}

/// `internal -> aggregate(temporality: cumulative) -> prometheus_out`: a `logit.component.*`
/// self-telemetry counter renders as an ordinary counter family, so `prometheus_out` is one more
/// sink the graph feeds, not a second telemetry representation. See
/// [ADR `internal-telemetry-as-pipeline-events`](../../../docs/adr/internal-telemetry-as-pipeline-events.md)'s
/// "Amendment: a `prometheus_out` sink is not the rejected scrape endpoint" section.
#[tokio::test]
async fn internal_telemetry_through_cumulative_aggregate_renders_a_logit_component_counter() {
    let registry = Registry::new();
    let telemetry = registry.telemetry_for("probe", "statsd_in", "listener");
    telemetry.count("logit.component.batches.sent", 3.0, &[]);

    let mut input = InternalInput::new(Duration::from_millis(20), registry);
    let (tx, mut rx) = mpsc::channel(16);
    let sink = Fanout::new(vec![tx]);
    tokio::spawn(async move {
        let _ = input.run(sink).await;
    });

    let delivered = tokio::time::timeout(Duration::from_secs(2), rx.recv())
        .await
        .expect("internal should drain and forward a batch")
        .expect("the Fanout channel should not have closed");
    let batch = logit_pipeline::unwrap_batch(delivered);

    let mut aggregator = Aggregator::new(Duration::from_secs(3600))
        .with_temporality(AggregateTemporality::Cumulative)
        .with_series_retention(5, 10_000);

    let mut passthrough = Vec::new();
    for mut event in batch.events {
        if aggregator.process(&batch.resource, &mut event) {
            passthrough.push(event);
        }
    }

    let flushed = aggregator.flush(1_700_000_000_000_000_000);
    let mut batches: Vec<EventBatch> = flushed
        .into_iter()
        .map(|(resource, scope, events)| EventBatch {
            resource,
            scope,
            events: events.into_iter().map(|(event, _links)| event).collect(),
        })
        .collect();
    if !passthrough.is_empty() {
        batches.push(EventBatch {
            resource: batch.resource.clone(),
            scope: batch.scope.clone(),
            events: passthrough,
        });
    }

    let (body, _addr) = expose_and_fetch(&batches, ACCEPT_TEXT).await;
    assert!(
        body.contains("logit_component_batches_sent_total"),
        "expected at least one logit_component_* counter family, got:\n{body}"
    );
}

/// `aggregate -> prometheus_out`: a series keeps its first record's `description`, which the
/// exposition renders as `# HELP`, on both the tumbling (gauge, no retention) and the retained
/// (cumulative counter) flush paths.
#[tokio::test]
async fn aggregate_carries_the_first_records_description_into_help() {
    use logit_core::interner::intern;
    use logit_core::{AttrMap, Event, MetricKind, MetricRecord, Resource};
    use std::sync::Arc;

    let record = |name: &str, kind: MetricKind, description: &str| {
        let mut record = MetricRecord::new(intern(name), kind);
        record.description = Some(intern(description));
        record
    };
    let resource = Arc::new(Resource::default());
    let mut tumbling = Aggregator::new(Duration::from_secs(10));
    let mut retained = Aggregator::new(Duration::from_secs(10))
        .with_temporality(AggregateTemporality::Cumulative)
        .with_series_retention(5, 100);
    for (i, description) in ["Queue depth.", "A later description."].into_iter().enumerate() {
        let gauge = record("depth", MetricKind::Gauge(i as f64), description);
        assert!(!tumbling.process(&resource, &mut Event::metric(0, AttrMap::new(), gauge)));
    }
    let hits = record("hits", MetricKind::counter(1.0), "Requests served.");
    assert!(!retained.process(&resource, &mut Event::metric(0, AttrMap::new(), hits)));

    let now = 1_700_000_000_000_000_000;
    let batches: Vec<EventBatch> = [tumbling.flush(now), retained.flush(now)]
        .into_iter()
        .flatten()
        .map(|(resource, scope, events)| EventBatch {
            resource,
            scope,
            events: events.into_iter().map(|(event, _links)| event).collect(),
        })
        .collect();

    let (body, _addr) = expose_and_fetch(&batches, ACCEPT_TEXT).await;
    assert!(body.contains("# HELP depth Queue depth."), "the first record's, got:\n{body}");
    assert!(body.contains("# HELP hits_total Requests served."), "got:\n{body}");
}

/// `aggregate -> prometheus_out`: a cumulative series the cardinality cap evicts and a later event
/// with source timestamp `0` re-creates renders `_created` as the start of the window it reopened
/// in, not `0` and not before the point it replaces.
#[tokio::test]
async fn a_re_created_cumulative_series_renders_created_at_its_window_start() {
    use logit_core::interner::intern;
    use logit_core::{AttrMap, Event, MetricKind, MetricRecord, Resource};
    use std::sync::Arc;

    let resource = Arc::new(Resource::default());
    // A cap of 1 keeps `anchor`, opened first, and evicts `hits` at every flush.
    let mut aggregator = Aggregator::new(Duration::from_secs(10))
        .with_temporality(AggregateTemporality::Cumulative)
        .with_series_retention(5, 1);
    let feed = |aggregator: &mut Aggregator, timestamp: i64| {
        for name in ["anchor", "hits"] {
            let record = MetricRecord::new(intern(name), MetricKind::counter(1.0));
            let mut event = Event::metric(timestamp, AttrMap::new(), record);
            assert!(!aggregator.process(&resource, &mut event));
        }
    };
    let first_flush = 1_700_000_000_000_000_000;
    feed(&mut aggregator, first_flush - 1);
    aggregator.flush(first_flush);
    feed(&mut aggregator, 0);
    let batches: Vec<EventBatch> = aggregator
        .flush(first_flush + 10_000_000_000)
        .into_iter()
        .map(|(resource, scope, events)| EventBatch {
            resource,
            scope,
            events: events.into_iter().map(|(event, _links)| event).collect(),
        })
        .collect();

    let (body, _addr) = expose_and_fetch(&batches, ACCEPT_OM).await;
    assert!(body.contains("hits_total 1"), "the re-created series restarts, got:\n{body}");
    let created: f64 = body
        .lines()
        .find_map(|line| line.strip_prefix("hits_created "))
        .unwrap_or_else(|| panic!("expected a hits_created line, got:\n{body}"))
        .trim()
        .parse()
        .expect("hits_created parses as a float");
    assert_eq!(created, 1.7e9, "the first flush's clock, in:\n{body}");
}
