// -- the harness ----------------------------------------------------------------------------------

fn direct_batch(raw: &[u8]) -> EventBatch {
    let mut decoder = CollectdDecoder::new(Arc::new(Resource::default()));
    decoder.decode(Bytes::copy_from_slice(raw)).expect("fixture should decode")
}

/// [`direct_batch`] for several datagrams: one decoder, one `decode_into` per datagram (each
/// resets the sticky state, as a listener's successive receives do), flattened into one
/// `EventBatch`, the shape a `BatchAccumulator` hands a sink.
fn direct_batch_multi(datagrams: &[Vec<u8>]) -> EventBatch {
    let resource = Arc::new(Resource::default());
    let mut decoder = CollectdDecoder::new(resource.clone());
    let mut events = Vec::new();
    for datagram in datagrams {
        decoder
            .decode_into(Bytes::copy_from_slice(datagram), 0, &mut events)
            .expect("fixture datagram should decode");
    }
    EventBatch { resource, scope: None, events }
}

/// A plain UDP capture socket (the raw-bytes half of each assertion) beside a bound, live
/// [`CollectdInput`] draining into a [`Fanout`] channel (the decoded-`EventBatch` half). The input
/// is bound, then `local_addr()` read, then spawned, so there is no bind-drop race.
///
/// Unlike the syslog and statsd harnesses, there's no `normalize_receipt_time`: every
/// byte-for-byte fixture carries a wire `Time`/`TimeHR`, so `Event::timestamp` is origin data and
/// compares equal. `no-time` is decode-only.
struct Harness {
    capture: UdpSocket,
    capture_addr: SocketAddr,
    input_addr: SocketAddr,
    rx: mpsc::Receiver<Delivered>,
}

/// How long to wait for a send's first datagram or batch, and then for each further one.
/// `SUBSEQUENT` bounds the "and nothing else came" assertions.
const FIRST: Duration = Duration::from_millis(500);
const SUBSEQUENT: Duration = Duration::from_millis(200);

impl Harness {
    async fn new() -> Self {
        let capture = UdpSocket::bind("127.0.0.1:0").await.expect("binding the capture socket");
        let capture_addr = capture.local_addr().expect("capture socket should have a local addr");

        let mut input = CollectdInput::new("127.0.0.1:0");
        input.bind().await.expect("binding the collectd_in listener");
        let input_addr = input.local_addr().expect("bind() should leave a real address behind");

        let (tx, rx) = mpsc::channel(64);
        let sink = Fanout::new(vec![tx]);
        tokio::spawn(async move {
            let _ = input.run(sink).await;
        });

        Self { capture, capture_addr, input_addr, rx }
    }

    /// A harness whose [`CollectdInput`] carries `diag`, for the decode-only cases.
    async fn with_diagnostics(diag: Diagnostics) -> Self {
        let capture = UdpSocket::bind("127.0.0.1:0").await.expect("binding the capture socket");
        let capture_addr = capture.local_addr().expect("capture socket should have a local addr");

        let mut input = CollectdInput::new("127.0.0.1:0").with_diagnostics(diag);
        input.bind().await.expect("binding the collectd_in listener");
        let input_addr = input.local_addr().expect("bind() should leave a real address behind");

        let (tx, rx) = mpsc::channel(64);
        let sink = Fanout::new(vec![tx]);
        tokio::spawn(async move {
            let _ = input.run(sink).await;
        });

        Self { capture, capture_addr, input_addr, rx }
    }

    /// Sends `batch` once to the capture socket and once to the live `collectd_in`, each through a
    /// fresh [`CollectdOutput`] passed through `configure` (a sink owns its socket, so it can't
    /// serve both legs), and returns every captured datagram and the decode.
    async fn round_trip_with(
        &mut self,
        batch: &EventBatch,
        configure: impl Fn(CollectdOutput) -> CollectdOutput,
    ) -> (Vec<Vec<u8>>, EventBatch) {
        let captured = self.capture_only(batch, &configure).await;

        let mut to_input = configure(CollectdOutput::udp(self.input_addr.to_string()).unwrap());
        to_input.send(batch).await.expect("send to the live collectd_in");
        (captured, self.drain_decoded().await)
    }

    /// [`Harness::round_trip_with`] with `collectd_out`'s defaults (`max_packet_bytes: 1452`, no
    /// `hostname:`).
    async fn round_trip(&mut self, batch: &EventBatch) -> (Vec<Vec<u8>>, EventBatch) {
        self.round_trip_with(batch, |sink| sink).await
    }

    /// Sends `batch` to the capture socket only, returning every datagram it received.
    async fn capture_only(
        &mut self,
        batch: &EventBatch,
        configure: impl Fn(CollectdOutput) -> CollectdOutput,
    ) -> Vec<Vec<u8>> {
        let mut to_capture = configure(CollectdOutput::udp(self.capture_addr.to_string()).unwrap());
        to_capture.send(batch).await.expect("send to the capture socket");
        self.drain_captured().await
    }

    /// Every datagram the capture socket holds: the first waited on for [`FIRST`], each later one
    /// for [`SUBSEQUENT`].
    async fn drain_captured(&mut self) -> Vec<Vec<u8>> {
        let mut buf = vec![0u8; 65_536];
        let mut datagrams = Vec::new();
        let mut wait = FIRST;
        while let Ok(result) = tokio::time::timeout(wait, self.capture.recv_from(&mut buf)).await {
            let (n, _) = result.expect("recv_from should succeed");
            datagrams.push(buf[..n].to_vec());
            wait = SUBSEQUENT;
        }
        assert!(!datagrams.is_empty(), "the capture socket received no datagram at all");
        datagrams
    }

    /// Every batch the live `collectd_in` delivered, merged into one: how a multi-datagram send is
    /// batched isn't this test's concern.
    async fn drain_decoded(&mut self) -> EventBatch {
        let mut batches = Vec::new();
        let mut wait = FIRST;
        while let Ok(delivered) = tokio::time::timeout(wait, self.rx.recv()).await {
            let delivered = delivered.expect("the Fanout channel should not have closed");
            batches.push(logit_pipeline::unwrap_batch(delivered));
            wait = SUBSEQUENT;
        }
        assert!(!batches.is_empty(), "collectd_in delivered nothing at all");
        let mut merged = batches.remove(0);
        for batch in batches {
            assert_eq!(batch.resource, merged.resource, "one decoder, one shared resource");
            assert!(batch.scope.is_none(), "collectd carries no scope concept");
            merged.events.extend(batch.events);
        }
        merged
    }

    /// Sends `raw` straight to the live `collectd_in`, for the decode-only cases: bytes no encoder
    /// would produce.
    async fn send_raw(&self, raw: &[u8]) {
        let sender =
            UdpSocket::bind("127.0.0.1:0").await.expect("binding an ephemeral sender socket");
        sender.send_to(raw, self.input_addr).await.expect("sending the raw datagram");
    }
}

/// Whether `registry` recorded a point named `metric` carrying `tag`. Drains, so call once.
fn counted(registry: &Registry, metric: &str, tag: (&str, &str)) -> bool {
    registry.drain(0).into_iter().any(|event| {
        event.metrics.iter().any(|m| logit_core::interner::resolve(m.name) == metric)
            && event.attributes.get(tag.0).and_then(Value::as_str) == Some(tag.1)
    })
}

/// The summed value of every point named `metric` carrying `tag` in `events`. Takes an
/// already-drained slice because `Registry::drain` empties the registry.
fn metric_sum(events: &[logit_core::Event], metric: &str, tag: (&str, &str)) -> f64 {
    events
        .iter()
        .filter(|e| e.attributes.get(tag.0).and_then(Value::as_str) == Some(tag.1))
        .flat_map(|e| &e.metrics)
        .filter(|m| logit_core::interner::resolve(m.name) == metric)
        .map(|m| match &m.kind {
            MetricKind::Sum(sum) => sum.value,
            other => panic!("{metric} must be a counter, got {other:?}"),
        })
        .sum()
}

fn attr(event: &logit_core::Event, key: &str) -> Option<Value> {
    event.attributes.get(key).cloned()
}

fn name_of(record: &logit_core::MetricRecord) -> &'static str {
    logit_core::interner::resolve(record.name)
}

