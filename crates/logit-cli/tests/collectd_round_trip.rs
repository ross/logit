/// The `.expected` marker meaning "byte-identical to the `.in` file" -- see this file's module doc,
/// mirroring `syslog_round_trip.rs`/`statsd_round_trip.rs`'s identical constant.
const SAME_AS_INPUT: &[u8] = b"== SAME AS INPUT ==";

// -- the wire, written by hand -------------------------------------------------------------------
//
// Deliberately *not* `logit_proto::collectd::part`'s writers: a fixture built by the same code the
// encoder uses could not prove the encoder writes what a real collectd sender does, and could not
// express the legacy and malformed shapes this corpus needs. Same stance
// `crates/logit-proto/tests/collectd_fixed_point.rs` takes for its own grammar.

const TYPE_HOST: u16 = 0x0000;
const TYPE_TIME: u16 = 0x0001;
const TYPE_PLUGIN: u16 = 0x0002;
const TYPE_PLUGIN_INSTANCE: u16 = 0x0003;
const TYPE_TYPE: u16 = 0x0004;
const TYPE_TYPE_INSTANCE: u16 = 0x0005;
const TYPE_VALUES: u16 = 0x0006;
const TYPE_INTERVAL: u16 = 0x0007;
const TYPE_TIME_HR: u16 = 0x0008;
const TYPE_INTERVAL_HR: u16 = 0x0009;
const TYPE_SIGNATURE: u16 = 0x0200;
const TYPE_ENCRYPTION: u16 = 0x0210;
/// A part type no collectd defines -- normalization 5's "unknown part types are skipped by length."
const TYPE_FROM_THE_FUTURE: u16 = 0x00FF;

/// Bytes of a numeric part: the four-byte header plus one `u64` BE.
const NUMBER_PART_LEN: usize = 12;

const DS_COUNTER: u8 = 0;
const DS_GAUGE: u8 = 1;
const DS_DERIVE: u8 = 2;
const DS_ABSOLUTE: u8 = 3;

/// `2023-11-14T22:13:20Z` in whole seconds, the instant every fixture in this corpus is stamped
/// with -- far enough from "now" that a receipt-time fallback (normalization 7) is unmistakable.
const TIME_SECONDS: u64 = 1_700_000_000;
/// [`TIME_SECONDS`] as a `cdtime_t`.
const TIME_HR: u64 = TIME_SECONDS << 30;
/// A ten-second `Interval`, as a `cdtime_t`.
const INTERVAL_HR: u64 = 10 << 30;
/// The sub-second half of `sub-second-time`'s `TimeHR`. Not an arbitrary bit pattern: most tick
/// values survive `cdtime → ns → cdtime` untouched, and a fixture that happened to pick one would
/// claim to exercise normalization 2 while exercising nothing at all. This one moves by exactly
/// one tick on the first hop (and is then stable), which is what
/// [`a_sub_second_time_moves_at_most_one_tick_and_is_then_stable`] asserts.
const SUB_SECOND_TICKS: u64 = 0x1234_567E;

#[derive(Default)]
struct PacketBuilder {
    bytes: Vec<u8>,
}

impl PacketBuilder {
    fn new() -> Self {
        Self::default()
    }

    /// `type: u16 BE, len: u16 BE` (the length *including* these four bytes), then the payload.
    fn part(mut self, part_type: u16, payload: &[u8]) -> Self {
        let len = (4 + payload.len()) as u16;
        self.bytes.extend_from_slice(&part_type.to_be_bytes());
        self.bytes.extend_from_slice(&len.to_be_bytes());
        self.bytes.extend_from_slice(payload);
        self
    }

    /// A NUL-terminated string part. An empty `value` is the five-byte part a sender writes to
    /// *clear* a sticky field, which is not the same as omitting the part.
    fn string(self, part_type: u16, value: &[u8]) -> Self {
        let mut payload = value.to_vec();
        payload.push(0);
        self.part(part_type, &payload)
    }

    /// A `u64`-BE numeric part.
    fn number(self, part_type: u16, value: u64) -> Self {
        self.part(part_type, &value.to_be_bytes())
    }

    /// A Values part: the `u16` data-source count, then every type byte, then every eight-byte
    /// value -- two vectors, not interleaved pairs.
    fn values(self, values: &[(u8, [u8; 8])]) -> Self {
        let mut payload = Vec::new();
        payload.extend_from_slice(&(values.len() as u16).to_be_bytes());
        for (ds_type, _) in values {
            payload.push(*ds_type);
        }
        for (_, raw) in values {
            payload.extend_from_slice(raw);
        }
        self.part(TYPE_VALUES, &payload)
    }

    /// Raw bytes with no framing at all -- for the deliberately malformed tail
    /// `truncated-values` ends in.
    fn raw(mut self, bytes: &[u8]) -> Self {
        self.bytes.extend_from_slice(bytes);
        self
    }

    fn build(self) -> Vec<u8> {
        self.bytes
    }
}

fn gauge(value: f64) -> (u8, [u8; 8]) {
    // Little-endian, unlike every other value type on this wire -- collectd writes `htole64` for
    // gauges specifically.
    (DS_GAUGE, value.to_le_bytes())
}

/// A GAUGE carrying an exact NaN *bit pattern*, which `f64::to_le_bytes` could not be trusted to
/// preserve through a `f64` literal.
fn gauge_bits(bits: u64) -> (u8, [u8; 8]) {
    (DS_GAUGE, bits.to_le_bytes())
}

fn counter(value: u64) -> (u8, [u8; 8]) {
    (DS_COUNTER, value.to_be_bytes())
}

fn derive(value: i64) -> (u8, [u8; 8]) {
    (DS_DERIVE, value.to_be_bytes())
}

fn absolute(value: u64) -> (u8, [u8; 8]) {
    (DS_ABSOLUTE, value.to_be_bytes())
}

/// Every `.in` file in the corpus, as the bytes a real sender would write. The committed files are
/// pinned against this by [`every_committed_in_file_matches_its_builder`]; this function is the
/// readable half of the corpus, and the files are the reviewable one.
///
/// Part order throughout is collectd's own `add_to_buffer` order -- Host, Time, Interval, Plugin,
/// PluginInstance, Type, TypeInstance, Values -- which is also the order `collectd_out` writes, so
/// a fixture that changes nothing else stays [`SAME_AS_INPUT`].
fn build_in(name: &str) -> Vec<u8> {
    match name {
        // -- byte for byte ---------------------------------------------------------------------
        "single-gauge" => PacketBuilder::new()
            .string(TYPE_HOST, b"web-1")
            .number(TYPE_TIME_HR, TIME_HR)
            .number(TYPE_INTERVAL_HR, INTERVAL_HR)
            .string(TYPE_PLUGIN, b"memory")
            .string(TYPE_TYPE, b"memory")
            .string(TYPE_TYPE_INSTANCE, b"used")
            .values(&[gauge(1.5)])
            .build(),

        // The legacy second-resolution pair, which no modern collectd writes but every one still
        // accepts -- and which this codec re-emits only as TimeHR/IntervalHR (normalization 1).
        "legacy-time-interval" => PacketBuilder::new()
            .string(TYPE_HOST, b"web-1")
            .number(TYPE_TIME, TIME_SECONDS)
            .number(TYPE_INTERVAL, 10)
            .string(TYPE_PLUGIN, b"cpu")
            .string(TYPE_PLUGIN_INSTANCE, b"0")
            .string(TYPE_TYPE, b"cpu")
            .string(TYPE_TYPE_INSTANCE, b"user")
            .values(&[derive(12_345)])
            .build(),

        // `load`'s three data sources: one Values part, therefore one event carrying three records
        // in wire order, therefore one Values part again on the way out.
        "multi-value-load" => PacketBuilder::new()
            .string(TYPE_HOST, b"web-1")
            .number(TYPE_TIME_HR, TIME_HR)
            .number(TYPE_INTERVAL_HR, INTERVAL_HR)
            .string(TYPE_PLUGIN, b"load")
            .string(TYPE_TYPE, b"load")
            .values(&[gauge(0.05), gauge(0.15), gauge(0.25)])
            .build(),

        // Both values stay inside 2^53, where an `i64` is exactly representable as an `f64` -- above
        // it the model's own int/double collapse (`docs/known-gaps.md`) would move the value, which
        // is a documented gap rather than anything this corpus should assert byte-equality across.
        "if-octets-derive" => PacketBuilder::new()
            .string(TYPE_HOST, b"web-1")
            .number(TYPE_TIME_HR, TIME_HR)
            .number(TYPE_INTERVAL_HR, INTERVAL_HR)
            .string(TYPE_PLUGIN, b"interface")
            .string(TYPE_PLUGIN_INSTANCE, b"eth0")
            .string(TYPE_TYPE, b"if_octets")
            .values(&[derive(1_234_567_890_123), derive(-42)])
            .build(),

        // `u64::MAX` is the one COUNTER that only survives because `as_u64`'s upper bound is
        // inclusive and the `as` cast saturates: it decodes to the `f64` 2^64 (the nearest
        // representable double), which an exclusive bound would drop.
        "counter-and-absolute" => PacketBuilder::new()
            .string(TYPE_HOST, b"web-1")
            .number(TYPE_TIME_HR, TIME_HR)
            .number(TYPE_INTERVAL_HR, INTERVAL_HR)
            .string(TYPE_PLUGIN, b"disk")
            .string(TYPE_PLUGIN_INSTANCE, b"sda")
            .string(TYPE_TYPE, b"disk_ops")
            .values(&[counter(u64::MAX), absolute(17)])
            .build(),

        // Three lists sharing one identity, only `TypeInstance` moving -- the protocol's whole
        // compression scheme. See the module doc for why TimeHR/IntervalHR are re-stated per list.
        "elided-identity" => PacketBuilder::new()
            .string(TYPE_HOST, b"web-1")
            .number(TYPE_TIME_HR, TIME_HR)
            .number(TYPE_INTERVAL_HR, INTERVAL_HR)
            .string(TYPE_PLUGIN, b"cpu")
            .string(TYPE_PLUGIN_INSTANCE, b"0")
            .string(TYPE_TYPE, b"cpu")
            .string(TYPE_TYPE_INSTANCE, b"user")
            .values(&[derive(100)])
            .number(TYPE_TIME_HR, TIME_HR)
            .number(TYPE_INTERVAL_HR, INTERVAL_HR)
            .string(TYPE_TYPE_INSTANCE, b"system")
            .values(&[derive(50)])
            .number(TYPE_TIME_HR, TIME_HR)
            .number(TYPE_INTERVAL_HR, INTERVAL_HR)
            .string(TYPE_TYPE_INSTANCE, b"idle")
            .values(&[derive(900)])
            .build(),

        // The elision a real collectd actually performs, and the one `collectd_out` does not
        // reproduce: `TimeHR`/`IntervalHR` stated once, inherited by the second list. Normalization
        // 10 -- the `.expected` re-states both, 24 bytes larger than what arrived.
        "elided-time-interval" => PacketBuilder::new()
            .string(TYPE_HOST, b"web-1")
            .number(TYPE_TIME_HR, TIME_HR)
            .number(TYPE_INTERVAL_HR, INTERVAL_HR)
            .string(TYPE_PLUGIN, b"cpu")
            .string(TYPE_PLUGIN_INSTANCE, b"0")
            .string(TYPE_TYPE, b"cpu")
            .string(TYPE_TYPE_INSTANCE, b"user")
            .values(&[derive(100)])
            .string(TYPE_TYPE_INSTANCE, b"system")
            .values(&[derive(50)])
            .build(),

        // Two five-byte string parts carrying nothing but their NUL: how a sender *clears* a
        // sticky instance it set earlier in the same datagram.
        "empty-instances" => PacketBuilder::new()
            .string(TYPE_HOST, b"web-1")
            .number(TYPE_TIME_HR, TIME_HR)
            .number(TYPE_INTERVAL_HR, INTERVAL_HR)
            .string(TYPE_PLUGIN, b"df")
            .string(TYPE_PLUGIN_INSTANCE, b"")
            .string(TYPE_TYPE, b"df_complex")
            .string(TYPE_TYPE_INSTANCE, b"")
            .values(&[gauge(1024.0)])
            .build(),

        // No Interval part of either resolution -- collectd's `network` plugin omits one when the
        // value list's own interval matches the daemon's global default. Normalization 9: the
        // `.expected` gains an explicit `IntervalHR 0`, collectd's own "unspecified", on each list.
        // `TimeHR` is deliberately re-stated on the second list so the *only* difference between
        // `.in` and `.expected` is normalization 9, not 10 as well.
        "no-interval" => PacketBuilder::new()
            .string(TYPE_HOST, b"web-1")
            .number(TYPE_TIME_HR, TIME_HR)
            .string(TYPE_PLUGIN, b"memory")
            .string(TYPE_TYPE, b"memory")
            .string(TYPE_TYPE_INSTANCE, b"used")
            .values(&[gauge(1.5)])
            .number(TYPE_TIME_HR, TIME_HR)
            .string(TYPE_TYPE_INSTANCE, b"free")
            .values(&[gauge(2.5)])
            .build(),

        // Normalization 8's substitution half, reachable from a real decode: collectd's own
        // receiver runs `escape_slashes` over an identity it accepts, so a sender that writes a
        // raw path -- a `df` plugin instance, a mount point -- is writing something every receiver
        // rewrites. This codec does the rewriting on egress instead, and counts it. Genuinely
        // one-way: the `/` is gone, so this fixture asserts wire bytes only.
        "slash-in-plugin" => PacketBuilder::new()
            .string(TYPE_HOST, b"web-1")
            .number(TYPE_TIME_HR, TIME_HR)
            .number(TYPE_INTERVAL_HR, INTERVAL_HR)
            .string(TYPE_PLUGIN, b"mount/data")
            .string(TYPE_TYPE, b"df_complex")
            .string(TYPE_TYPE_INSTANCE, b"/var/log")
            .values(&[gauge(7.0)])
            .build(),

        // collectd's strings are bytes, not text: a host name from a non-UTF-8 locale is a real
        // thing to receive.
        "non-utf8-host" => PacketBuilder::new()
            .string(TYPE_HOST, b"web-\xff-1")
            .number(TYPE_TIME_HR, TIME_HR)
            .number(TYPE_INTERVAL_HR, INTERVAL_HR)
            .string(TYPE_PLUGIN, b"memory")
            .string(TYPE_TYPE, b"memory")
            .string(TYPE_TYPE_INSTANCE, b"free")
            .values(&[gauge(2.5)])
            .build(),

        // A part type from a collectd newer than this codec, and a `SecurityLevel Sign` sender's
        // Signature part (an HMAC-SHA256 over the plaintext that follows, then the username) --
        // both skipped by length, both dropped on egress, and the list behind them still decodes.
        "unknown-and-signature-parts" => PacketBuilder::new()
            .string(TYPE_HOST, b"web-1")
            .number(TYPE_TIME_HR, TIME_HR)
            .number(TYPE_INTERVAL_HR, INTERVAL_HR)
            .string(TYPE_PLUGIN, b"swap")
            .string(TYPE_TYPE, b"swap")
            .string(TYPE_TYPE_INSTANCE, b"used")
            .values(&[gauge(100.0)])
            .part(TYPE_FROM_THE_FUTURE, b"a part type this codec has never heard of")
            .part(TYPE_SIGNATURE, &{
                let mut payload = vec![0xABu8; 32];
                payload.extend_from_slice(b"fixture-user");
                payload
            })
            .number(TYPE_TIME_HR, TIME_HR)
            .number(TYPE_INTERVAL_HR, INTERVAL_HR)
            .string(TYPE_TYPE_INSTANCE, b"free")
            .values(&[gauge(200.0)])
            .build(),

        // A negative quiet NaN with a live payload bit: collectd's "no value this interval," spelt
        // in a bit pattern that is not the one this platform's `f64::NAN` has.
        "nan-gauge" => PacketBuilder::new()
            .string(TYPE_HOST, b"web-1")
            .number(TYPE_TIME_HR, TIME_HR)
            .number(TYPE_INTERVAL_HR, INTERVAL_HR)
            .string(TYPE_PLUGIN, b"sensors")
            .string(TYPE_PLUGIN_INSTANCE, b"coretemp")
            .string(TYPE_TYPE, b"temperature")
            .string(TYPE_TYPE_INSTANCE, b"core0")
            .values(&[gauge_bits(0xFFF8_0000_0000_0001)])
            .build(),

        // Every low bit of the cdtime live, which is what reaches normalization 2 -- a whole-second
        // TimeHR is bit-identical to its own legacy spelling and can never move.
        "sub-second-time" => PacketBuilder::new()
            .string(TYPE_HOST, b"web-1")
            .number(TYPE_TIME_HR, TIME_HR | SUB_SECOND_TICKS)
            .number(TYPE_INTERVAL_HR, INTERVAL_HR)
            .string(TYPE_PLUGIN, b"processes")
            .string(TYPE_TYPE, b"ps_state")
            .string(TYPE_TYPE_INSTANCE, b"running")
            .values(&[gauge(42.0)])
            .build(),

        // 30 lists in one datagram that fits collectd's own 1452-byte default, carrying no interval
        // at all (normalization 9 on the way out) purely so all 30 fit. The sink re-packs them at
        // 1024.
        "repacked-at-1024" => {
            let mut builder = PacketBuilder::new()
                .string(TYPE_HOST, b"web-1")
                .number(TYPE_TIME_HR, TIME_HR)
                .string(TYPE_PLUGIN, b"cpu")
                .string(TYPE_PLUGIN_INSTANCE, b"0")
                .string(TYPE_TYPE, b"cpu");
            for index in 0..30u64 {
                if index > 0 {
                    builder = builder.number(TYPE_TIME_HR, TIME_HR);
                }
                builder = builder
                    .string(TYPE_TYPE_INSTANCE, format!("state-{index:02}-of-30").as_bytes())
                    .values(&[derive(index as i64 * 1000)]);
            }
            builder.build()
        }

        // -- decode only -------------------------------------------------------------------------

        // The second list is ciphertext as far as this codec is concerned, and must never decode.
        "encrypted" => PacketBuilder::new()
            .string(TYPE_HOST, b"web-1")
            .number(TYPE_TIME_HR, TIME_HR)
            .number(TYPE_INTERVAL_HR, INTERVAL_HR)
            .string(TYPE_PLUGIN, b"uptime")
            .string(TYPE_TYPE, b"uptime")
            .values(&[gauge(3600.0)])
            .part(TYPE_ENCRYPTION, &[0x5A; 48])
            .values(&[gauge(7200.0)])
            .build(),

        // No Time part of either resolution: normalization 7's receipt-time stamp.
        "no-time" => PacketBuilder::new()
            .string(TYPE_HOST, b"web-1")
            .string(TYPE_PLUGIN, b"memory")
            .string(TYPE_TYPE, b"memory")
            .string(TYPE_TYPE_INSTANCE, b"cached")
            .values(&[gauge(512.0)])
            .build(),

        // A Values header declaring 24 bytes with only six left in the datagram -- a packet cut
        // mid-part by a sender, a middlebox, or a hostile length.
        "truncated-values" => PacketBuilder::new()
            .string(TYPE_HOST, b"web-1")
            .number(TYPE_TIME_HR, TIME_HR)
            .number(TYPE_INTERVAL_HR, INTERVAL_HR)
            .string(TYPE_PLUGIN, b"load")
            .string(TYPE_TYPE, b"load")
            .values(&[gauge(0.5)])
            .raw(&[0x00, 0x06, 0x00, 0x18, 0x00, 0x02])
            .build(),

        // An empty Host part clears the sticky host, so the list behind it has no identity to
        // dispatch against -- exactly what collectd's own receiver rejects with `-EINVAL`.
        "incomplete-identity" => PacketBuilder::new()
            .string(TYPE_HOST, b"web-1")
            .number(TYPE_TIME_HR, TIME_HR)
            .number(TYPE_INTERVAL_HR, INTERVAL_HR)
            .string(TYPE_PLUGIN, b"load")
            .string(TYPE_TYPE, b"load")
            .values(&[gauge(0.5)])
            .string(TYPE_HOST, b"")
            .values(&[gauge(0.9)])
            .build(),

        other => panic!("no builder for fixture {other:?}"),
    }
}

/// The byte-for-byte cases: a `.in` and a `.expected` each, both halves asserted (captured
