//! `collectd_in -> collectd_out` round trip over real UDP sockets. The components run in-process
//! (a `CollectdOutput` sending to a bound, live `CollectdInput`), not through `logit run`. This
//! lives in `logit-cli` because it already depends on both `logit-inputs` and `logit-outputs`; a
//! dev-dependency between those two crates would be a cycle.
//!
//! This file proves the real sockets and components compose to the codec's fixed point. The
//! codec's own correctness is fixed-pointed and proptested in
//! `crates/logit-proto/tests/collectd_fixed_point.rs`. The fixed point is the one ADR
//! `lossless-transit` requires, modulo the numbered list in [`logit_proto::collectd`]'s module doc
//! (`crates/logit-proto/src/collectd/mod.rs`, "Permitted normalizations"), which is the canonical
//! copy; the tables below cite its numbers. ADR `collectd-binary-relay` numbers the same list one
//! higher from its (3) on, because it splits (3) in two.
//!
//! ## Fixture corpus (`tests/fixtures/collectd/`)
//!
//! One file pair per byte-for-byte case: `<name>.in` (a raw collectd datagram) and
//! `<name>.expected` (the datagram `collectd_out` must emit for that decode, or the marker
//! [`SAME_AS_INPUT`] when the sink reproduces the input verbatim). The decode-only cases and
//! `repacked-at-1024` have an `.in` only.
//!
//! The files are binary, so every `.in` is also built in code by [`build_in`]'s [`PacketBuilder`],
//! which is independent of `logit_proto::collectd::part`'s writers so a fixture tests the codec
//! against the protocol rather than against itself.
//! [`every_committed_in_file_matches_its_builder`] pins the committed bytes to the builder: read
//! [`build_in`] to see what a fixture is. Each `.expected` was generated by this harness and
//! reviewed as a hex dump, part by part, against the normalization list.
//!
//! The three `testdata/interop/collectd/*.raw` captures from a real Debian `collectd` aren't
//! copied here; `crates/logit-inputs/src/collectd.rs`'s `interop_fixture_*` tests replay them in
//! place. [`a_real_collectd_capture_grows_when_its_elided_time_parts_are_restored`] reads one of
//! them to pin what normalization 10 costs: a real sender elides unchanged `TimeHR`/`IntervalHR`
//! parts, `collectd_out` restates them on every list, and the 1296-byte `collectd-000.raw` relays
//! as 1717 bytes in two datagrams.
//!
//! ## Per-fixture normalizations
//!
//! Byte-for-byte cases: the captured datagram equals `.expected`, and the live decode equals the
//! original decode as a whole `EventBatch`.
//!
//! | Fixture | Normalizations | What it pins |
//! |---|---|---|
//! | `single-gauge` | none ([`SAME_AS_INPUT`]) | the baseline: one GAUGE list, `f64` little-endian, full identity, exact `TimeHR`/`IntervalHR` |
//! | `legacy-time-interval` | **1** | a second-resolution `Time`(0x0001)/`Interval`(0x0007) pair re-emitted as `TimeHR`(0x0008)/`IntervalHR`(0x0009) |
//! | `multi-value-load` | none ([`SAME_AS_INPUT`]) | a 3-data-source list is one event with three records in wire order, re-emitted as one list, not three |
//! | `if-octets-derive` | none ([`SAME_AS_INPUT`]) | a negative DERIVE (`i64`, big-endian) survives the `f64` model round trip |
//! | `counter-and-absolute` | none ([`SAME_AS_INPUT`]) | a `u64::MAX` COUNTER (see [`build_in`]) beside an ABSOLUTE |
//! | `elided-identity` | **3** | three lists differing only in `TypeInstance`; the sender's elision and the encoder's recomputed elision agree, so it stays [`SAME_AS_INPUT`] |
//! | `elided-time-interval` | **10** | two lists stating `TimeHR`/`IntervalHR` once, as a real sender does; the `.expected` restates both on the second list, +24 B |
//! | `empty-instances` | **3** | empty `PluginInstance`/`TypeInstance` parts (a sender clearing an instance) decode to absent attributes and are elided on egress |
//! | `no-interval` | **9** | two lists with no interval part; the `.expected` gains `IntervalHR 0` (collectd's "unspecified") on each, +24 B |
//! | `non-utf8-host` | none ([`SAME_AS_INPUT`]) | a `0xFF` in `Host` decodes to `Value::Bytes` and is re-emitted verbatim |
//! | `unknown-and-signature-parts` | **5** | an unknown `0x00FF` part and a `0x0200` Signature part between two lists: skipped by length, dropped on egress, and the list behind them still decodes |
//! | `nan-gauge` | **6** | a non-canonical NaN payload (`0xFFF8_0000_0000_0001`) decodes to a `NO_RECORDED_VALUE`-flagged `Gauge(0.0)` and leaves as this platform's canonical `f64::NAN` |
//! | `sub-second-time` | **2** | a `cdtime_t` whose sub-second bits move one 2⁻³⁰ s tick on the first hop; the second hop is byte-identical to the first |
//! | `notification-failure`/`-warning`/`-okay` | none ([`SAME_AS_INPUT`]) | one notification each, severity 1/2/4: an `Event::log` with `collectd.severity` and `LogRecord::severity` `Error`/`Warn`/`Info`, no metrics |
//!
//! One case is one-way lossy, so it asserts the `.expected` wire bytes only:
//!
//! | Fixture | Normalizations | What it pins |
//! |---|---|---|
//! | `slash-in-plugin` | **8** | a `Plugin` of `mount/data` and a `TypeInstance` of `/var/log` leave as `mount_data` and `_var_log` (collectd's own `escape_slashes`), counted `logit.output.identity.sanitized{reason="substituted"}` |
//!
//! One structural case, where the bytes are allowed to move:
//!
//! | Fixture | Normalizations | What it pins |
//! |---|---|---|
//! | `repacked-at-1024` | **3**, **9** | 30 lists in one 1412-byte input with no interval part, re-packed under a 1024-byte cap: ≥2 datagrams, none over the cap, whole-batch equality. No `.expected`, since the boundaries may move; `no-interval` pins the `IntervalHR 0` bytes |
//!
//! One multi-datagram case, whose `.in` and `.expected` each concatenate several datagrams
//! (built by [`notification_between_lists_datagrams`] and decoded one at a time, as a listener
//! receives them), with its own test:
//!
//! | Fixture | Normalizations | What it pins |
//! |---|---|---|
//! | `notification-between-lists` | **11** | list (`type_instance=free`), notification, list (no `type_instance`), decoded from three datagrams into one batch and relayed: the notification gets its own datagram, and the second list restates Host/Plugin/Type in full, neither eliding against the notification's identity nor inheriting the first list's `type_instance` |
//!
//! Decode-only cases, sent to the live `collectd_in` and asserted on the delivered events and the
//! [`Registry`]'s diagnostic counters:
//!
//! | Fixture | Diagnostic | What it pins |
//! |---|---|---|
//! | `encrypted` | `encrypted_packet_dropped` | a `0x0210` Encryption part stops the walk: the list before it is kept, the list behind it never decodes |
//! | `no-time` | none | normalization **7**: no `Time`/`TimeHR` part stamps `received_at` |
//! | `truncated-values` | `bad_part` | a `Values` header declaring more bytes than the datagram holds abandons the rest and keeps what was already decoded |
//! | `incomplete-identity` | `incomplete_identity` | an empty `Host` part clears the sticky host, and the list behind it is skipped, as collectd's own receiver does |
//!
//! ## What this corpus does *not* cover
//!
//! ADR `lossless-transit` reads "no fixture" as "not covered", so:
//!
//! - **Normalization 4 (list reordering within a batch)** has no fixture because this pair never
//!   reorders. `CollectdEncoder::encode_into` emits lists in `EventBatch::events` order, and
//!   `crates/logit-proto/tests/collectd_fixed_point.rs`'s `decode(encode(b)) == b` compares an
//!   ordered `Vec<Event>`. The entry licenses a downstream reorder (a `Fanout`, a buffered sink
//!   retry).
//!
//! ## Cross-protocol
//!
//! `statsd_in -> collectd_out` exercises the encoder's fallback path (no `collectd.*` identity),
//! including its two likeliest drops: a sampled counter's non-integral extrapolation, and a
//! DogStatsD tag, which collectd has no wire form for. `collectd_in -> aggregate -> collectd_out`
//! pins that a cumulative `Sum` (what COUNTER and DERIVE decode to) passes through `aggregate`
//! untouched, so the relay stays byte-identical with a window in the middle.

