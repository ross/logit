/// Normalization 7 from the decode side: a list with no `Time`/`TimeHR` part at all borrows the
/// datagram's receipt time. collectd's own receiver rejects such a list outright; `logit` observes
/// rather than polices, exactly as every other listener in the tree stamps receipt time.
